def parse_vehicle_data(vehicle_data):
    parsed_data = {
        "title": vehicle_data.get("title"),
        "price": vehicle_data.get("price", {}).get("grs", {}).get("localized"),
        "location": vehicle_data.get("attr", {}).get("loc"),
        "country": vehicle_data.get("attr", {}).get("cn"),
        "first_registration": vehicle_data.get("attr", {}).get("fr"),
        "power": vehicle_data.get("attr", {}).get("pw"),
        "fuel_type": vehicle_data.get("attr", {}).get("ft"),
        "mileage": vehicle_data.get("attr", {}).get("ml"),
        "transmission": vehicle_data.get("attr", {}).get("tr"),
        "color": vehicle_data.get("attr", {}).get("ecol"),
        "dealer_name": vehicle_data.get("contact", {}).get("name"),
        "dealer_contact": vehicle_data.get("contact", {}).get("phones", [{}])[0].get("number"),
        "rating": vehicle_data.get("contact", {}).get("rating", {}).get("score"),
        "rating_count": vehicle_data.get("contact", {}).get("rating", {}).get("count"),
        "highlights": vehicle_data.get("highlights", []),
        "link": vehicle_data.get("url"),
        "image_urls": [f"https://{img['uri']}" for img in vehicle_data.get("images", [])],
    }
    
    return parsed_data

